import turtle
t=turtle.Turtle()
t.fillcolor("light green")
t.begin_fill()
for _ in range(4):
 t.rt(90)
 t.fd(100)
t.end_fill()
t.fillcolor("red")
t.begin_fill()
t.lt(120)
t.fd(100)
t.lt(120)
t.fd(100)
t.end_fill()
t.lt(120)
t.up()
t.fd(100)
t.down()
t.lt(90)
t.fillcolor("green")
t.begin_fill()
t.fd(70)
t.lt(90)
t.fd(20)
t.lt(90)
t.fd(40)
t.end_fill()
t.up()
t.fd(130)
t.rt(90)
t.fd(40)
t.fillcolor("gold")
t.begin_fill()
t.rt(90)
t.fd(30)
t.rt(90)
t.fd(20)
t.rt(90)
t.fd(30)
t.end_fill()



turtle.mainloop()